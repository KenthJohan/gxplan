#ifndef GFX_RESULT_H
#define GFX_RESULT_H

/* Zero represents success; every other value identifies an error. */
typedef enum {
    GFX_OK = 0,
    GFX_ERROR_INVALID_ARGUMENT,
    GFX_ERROR_SIZE_OVERFLOW,
    GFX_ERROR_CAPACITY_EXCEEDED,
    GFX_ERROR_UNKNOWN_OPCODE,
    GFX_ERROR_INVALID_COMMAND_SIZE,
    GFX_ERROR_INVALID_PAYLOAD_SIZE,
    GFX_ERROR_INVALID_ORDER,
    GFX_ERROR_FRAME_WINDOW_MISMATCH,
    GFX_ERROR_NULL_STREAM,
    GFX_ERROR_TRUNCATED_HEADER,
    GFX_ERROR_INVALID_RECORD_SIZE,
    GFX_ERROR_TRUNCATED_RECORD,
    GFX_ERROR_INCOMPLETE_FRAME,
    GFX_ERROR_INCOMPLETE_PASS
} gfx_result_t;

#endif
